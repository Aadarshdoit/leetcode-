class Solution {
public:
    long long countCommas(long long n) {
        if (n<1000){
            return 0;
        }
        else if(n>999 && n<1000000){
            return n-999 ;
        }
        else if(n>=1000000 && n<1000000000){
            return (n-1000000 +1)*2 +999000 ;
        }
        else if(n>=1000000000 && n< 1000000000000){
            return (n-1000000000 +1)*3 + (999000 + (999000000 * 2)) ;
        }
        else if(n>=1000000000000 && n< 1000000000000000){
            return (n-1000000000000+1 )*4 + (999000 + (999000000 * 2) + (999000000000 *3));
        }
        else{
            return (n-1000000000000+1 )*4 + (999000 + (999000000 * 2) + (999000000000 *3) + 1);
        }
    }
};